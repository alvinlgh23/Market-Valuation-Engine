async function runCompany(command: "resolve" | "analyze" | "open" | "index", ticker?: string, refresh = false) {
  if (ticker && (!/^[A-Za-z0-9 .^=-]{1,100}$/.test(ticker) || ticker.startsWith("-"))) throw new PythonRuntimeError("INVALID_INPUT", "Invalid company query.");
  const args = ["-B", "company_research.py", command, ...(ticker ? [ticker] : []), ...(refresh ? ["--refresh"] : [])];
  const result = await runPythonJson<Record<string, unknown>>(args, 120_000);
  if (!result || typeof result !== "object" || Array.isArray(result) || (command === "resolve" && !result.resolution) || (command === "index" && !Array.isArray(result.recent_research)) || (["open", "analyze"].includes(command) && typeof result.status !== "string")) throw new PythonRuntimeError("INVALID_JSON", "Malformed company research payload.");
  return result;
}

const verdictCache = new Map<string, { at: number; value: unknown }>();
const VERDICT_CACHE_MS = 15 * 60 * 1000;

/** Checklist 8.1: the company judgment card, generated by company_verdict.py (records the card in signal history). */
async function runVerdict(ticker: string) {
  if (!/^[A-Za-z0-9.^=-]{1,12}$/.test(ticker) || ticker.startsWith("-")) throw new PythonRuntimeError("INVALID_INPUT", "Invalid ticker.");
  const key = ticker.toUpperCase();
  const cached = verdictCache.get(key);
  if (cached && Date.now() - cached.at < VERDICT_CACHE_MS) return cached.value;
  const cards = await runPythonJson<Array<Record<string, unknown>>>(["-B", "company_verdict.py", key, "--json"], 240_000);
  if (!Array.isArray(cards) || !cards[0]) throw new PythonRuntimeError("INVALID_JSON", "The judgment card returned no data.");
  verdictCache.set(key, { at: Date.now(), value: cards[0] });
  return cards[0];
}

let storyCache: { at: number; value: unknown } | null = null;
let storyInflight: Promise<unknown> | null = null;

/** Checklists 15-17: the market story, S&P 500 profit breakdown and scenario gate (market_story.py). */
async function runMarketStory() {
  if (storyCache && Date.now() - storyCache.at < VERDICT_CACHE_MS) return storyCache.value;
  storyInflight ??= runPythonJson<Record<string, unknown>>(["-B", "market_story.py", "--json"], 300_000)
    .then((value) => { if (!value || typeof value !== "object" || !("story" in value)) throw new PythonRuntimeError("INVALID_JSON", "The market story returned no data."); storyCache = { at: Date.now(), value }; return value; })
    .finally(() => { storyInflight = null; });
  return storyInflight;
}

// Checklist 19.1: ticker suggestions for adding to the watchlist, from the cached SEC company list.
let tickerIndex: Array<{ ticker: string; name: string }> | null = null;
async function searchTickers(query: string) {
  if (!tickerIndex) {
    try {
      const raw = JSON.parse(await readFile(path.resolve(process.cwd(), "..", ".cache", "sec_company", "company_tickers.json"), "utf8")) as Record<string, { ticker: string; title: string }>;
      tickerIndex = Object.values(raw).map((row) => ({ ticker: String(row.ticker).toUpperCase(), name: String(row.title) }));
    } catch { tickerIndex = []; }
  }
  const q = query.trim().toUpperCase();
  if (!q) return [];
  const exact = tickerIndex.filter((row) => row.ticker === q);
  const prefix = tickerIndex.filter((row) => row.ticker !== q && row.ticker.startsWith(q));
  const named = q.length >= 2 ? tickerIndex.filter((row) => !row.ticker.startsWith(q) && row.name.toUpperCase().includes(q)) : [];
  return [...exact, ...prefix, ...named].slice(0, 8);
}

export async function GET(request: NextRequest) {
  const action = request.nextUrl.searchParams.get("action");
  if (action === "ticker-search") return NextResponse.json({ status: "OK", results: await searchTickers(request.nextUrl.searchParams.get("q") ?? "") });
  if (action === "market-story") {
    try {
      return NextResponse.json({ status: "OK", ...(await runMarketStory() as Record<string, unknown>) });
    } catch (error) {
      return NextResponse.json({ status: "FAILED", runtime_error: runtimeError(error), error: runtimeError(error).message }, { status: 502 });
    }
  }
  if (action === "company-verdict" || action === "watchlist-summary" || action === "watchlist-drivers" || action === "fx-moves" || action === "watchlist-events") {
    try {
      if (action === "watchlist-events") return NextResponse.json({ status: "OK", ...(await runPythonJson<Record<string, unknown>>(["-B", "company_verdict.py", "--events"], 180_000)) });
      if (action === "fx-moves") return NextResponse.json({ status: "OK", fx: await runPythonJson<unknown>(["-B", "company_verdict.py", "--fx"], 120_000) });
      if (action === "watchlist-drivers") return NextResponse.json({ status: "OK", rows: await runPythonJson<unknown[]>(["-B", "company_verdict.py", "--drivers"], 240_000) });
      if (action === "watchlist-summary") return NextResponse.json({ status: "OK", rows: await runPythonJson<unknown[]>(["-B", "company_verdict.py", "--summary"], 60_000) });
      const ticker = request.nextUrl.searchParams.get("ticker")?.trim() ?? "";
      return NextResponse.json({ status: "OK", card: await runVerdict(ticker) });
    } catch (error) {
      return NextResponse.json({ status: "FAILED", runtime_error: runtimeError(error), error: runtimeError(error).message }, { status: 502 });
    }
  }
  if (action === "valuation-analyze") {
    const ticker = request.nextUrl.searchParams.get("ticker")?.trim();
    if (!ticker) return NextResponse.json({ status: "PROVIDER_ERROR", report: null, meta: { data_state: "UNAVAILABLE", source: "VALIDATION", error: "Ticker is required." } }, { status: 400 });
    const result = await analyzeValuation(ticker, { refresh: request.nextUrl.searchParams.get("refresh") === "1" });
    return NextResponse.json(result, { status: result.status === "PROVIDER_ERROR" ? 502 : 200 });
  }
  if (action?.startsWith("company-")) {
    const ticker = request.nextUrl.searchParams.get("ticker")?.trim();
    const command = action.replace("company-", "") as "resolve" | "open" | "index";
    if (!(["resolve", "open", "index"] as const).includes(command)) return NextResponse.json({ status: "FAILED", errors: ["Unsupported company research action."] }, { status: 400 });
    if (command !== "index" && !ticker) return NextResponse.json({ status: "FAILED", errors: ["Ticker is required."] }, { status: 400 });
    try {
      return NextResponse.json(await runCompany(command, ticker));
    } catch (error) {
      return NextResponse.json({ status: "FAILED", profile: null, runtime_error: runtimeError(error), errors: [runtimeError(error).message] }, { status: 502 });
    }
  }
  const refresh = request.nextUrl.searchParams.get("refresh") === "1";
  const scope = request.nextUrl.searchParams.get("scope") || "full";
  if (action || !["full", "dashboard", "world"].includes(scope)) return NextResponse.json({ status: "FAILED", runtime_error: { code: "UNSUPPORTED_ACTION", message: "Unsupported research action or scope." } }, { status: 400 });
  const result = await loadResearchSystem(refresh);
  const full = result.data;
  return NextResponse.json({ data: scope === "dashboard" ? full.dashboard : scope === "world" ? full.world : full, meta: result.meta });
}

// Checklist 18.15: the reader edits their own watchlist. Tickers are validated before data/watchlist.json is rewritten.
const TICKER = /^[A-Z][A-Z0-9.^=-]{0,11}$/;
const MAX_WATCHLIST = 40;
async function setWatchlist(tickers: unknown) {
  if (!Array.isArray(tickers)) return { status: 400, body: { status: "FAILED", errors: ["A list of tickers is required."] } };
  const clean = Array.from(new Set(tickers.map((item) => String(item ?? "").trim().toUpperCase()))).filter(Boolean);
  const invalid = clean.filter((item) => !TICKER.test(item));
  if (invalid.length) return { status: 400, body: { status: "FAILED", errors: [`Not a ticker: ${invalid.join(", ")}`] } };
  if (clean.length > MAX_WATCHLIST) return { status: 400, body: { status: "FAILED", errors: [`At most ${MAX_WATCHLIST} companies.`] } };
  const file = path.resolve(process.cwd(), "..", "data", "watchlist.json");
  let existing: Record<string, unknown> = {};
  try { existing = JSON.parse(await readFile(file, "utf8")) as Record<string, unknown>; } catch { existing = {}; }
  const temporary = `${file}.tmp`;
  // Same layout as the hand-written file (tickers on one line), so saving an unchanged list changes nothing.
  const others = Object.entries(existing).filter(([key]) => key !== "tickers").map(([key, value]) => `,\n  ${JSON.stringify(key)}: ${JSON.stringify(value)}`).join("");
  await writeFile(temporary, `{\n  "tickers": [${clean.map((item) => JSON.stringify(item)).join(", ")}]${others}\n}\n`);
  await rename(temporary, file);
  storyCache = null;   // the story's holdings step follows the list
  return { status: 200, body: { status: "OK", tickers: clean } };
}

export async function POST(request: NextRequest) {
  let body: { action?: string; ticker?: string; refresh?: boolean; overrides?: ValuationOverrides; tickers?: unknown };
  try {
    body = await request.json() as typeof body;
  } catch {
    return NextResponse.json({ status: "FAILED", errors: ["A JSON request body is required."] }, { status: 400 });
  }
  if (body?.action === "watchlist-set") {
    const result = await setWatchlist(body.tickers);
    return NextResponse.json(result.body, { status: result.status });
  }
  if (!body || typeof body.ticker !== "string" || !body.ticker.trim() || !["company-analyze", "valuation-analyze"].includes(body.action || "")) {
    return NextResponse.json({ status: "FAILED", errors: ["A supported action and ticker are required."] }, { status: 400 });
  }
  if (body.action === "valuation-analyze") {
    const result = await analyzeValuation(body.ticker, { refresh: Boolean(body.refresh), overrides: body.overrides });
    return NextResponse.json(result, { status: result.status === "PROVIDER_ERROR" ? 502 : 200 });
  }
  try {
    return NextResponse.json(await runCompany("analyze", body.ticker.trim(), Boolean(body.refresh)));
  } catch (error) {
    return NextResponse.json({ status: "FAILED", ticker: body.ticker.trim().toUpperCase(), profile: null, runtime_error: runtimeError(error), errors: [runtimeError(error).message] }, { status: 502 });
  }
}
